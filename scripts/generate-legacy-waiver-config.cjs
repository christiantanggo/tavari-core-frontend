/**
 * Writes generated config.js files for older-tablet static pages:
 * - public/waiver-browser-kiosk/config.js — Supabase anon + optional subdomain cutover URL
 * - public/legacy-kiosk-downloads/config.js — installer base URL for kiosk app downloads
 * - public/task-manager-kiosk/config.js — legacy task kiosk Supabase config
 * - public/legacy-punchclock/config.js — legacy punch clock Supabase config
 * Runs on prebuild/predev. Gitignored outputs — Vercel injects env at build time.
 */
const fs = require('fs');
const path = require('path');

const waiverOutDir = path.join(__dirname, '..', 'public', 'waiver-browser-kiosk');
const waiverOutFile = path.join(waiverOutDir, 'config.js');
const dlOutDir = path.join(__dirname, '..', 'public', 'legacy-kiosk-downloads');
const dlOutFile = path.join(dlOutDir, 'config.js');
const taskOutDir = path.join(__dirname, '..', 'public', 'task-manager-kiosk');
const taskOutFile = path.join(taskOutDir, 'config.js');
const punchOutDir = path.join(__dirname, '..', 'public', 'legacy-punchclock');
const punchOutFile = path.join(punchOutDir, 'config.js');

function loadEnvFile() {
  const envPath = path.join(__dirname, '..', '.env');
  const env = { ...process.env };
  if (!fs.existsSync(envPath)) return env;
  const text = fs.readFileSync(envPath, 'utf8');
  text.split(/\r?\n/).forEach(function (line) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
    if (!m) return;
    let v = m[2].trim();
    if ((v.charAt(0) === '"' && v.charAt(v.length - 1) === '"') || (v.charAt(0) === "'" && v.charAt(v.length - 1) === "'")) {
      v = v.slice(1, -1);
    }
    env[m[1]] = v;
  });
  return env;
}

const env = loadEnvFile();
const url = env.VITE_SUPABASE_URL || '';
const key = env.VITE_SUPABASE_ANON_KEY || '';
const publicAppUrl = (env.VITE_PUBLIC_APP_URL || '').trim().replace(/\/$/, '');
const waiverSubdomainUrl = (
  env.VITE_WAIVER_SUBDOMAIN_URL ||
  env.VITE_WAIVER_BROWSER_KIOSK_URL ||
  env.VITE_WAIVER_LEGACY_URL ||
  ''
).trim().replace(/\/$/, '');
const taskManagerSubdomainUrl = (
  env.VITE_TASK_MANAGER_SUBDOMAIN_URL ||
  env.VITE_TASK_MANAGER_KIOSK_URL ||
  'https://task-manager.tavarios.ca'
).trim().replace(/\/$/, '');
const legacyPunchClockSubdomainUrl = (
  env.VITE_LEGACY_PUNCHCLOCK_SUBDOMAIN_URL ||
  env.VITE_LEGACY_PUNCHCLOCK_URL ||
  'https://legacy-punchclock.tavarios.ca'
).trim().replace(/\/$/, '');
const legacyPunchClockBusinessId = (
  env.VITE_LEGACY_PUNCHCLOCK_BUSINESS_ID ||
  env.VITE_DEFAULT_BUSINESS_ID ||
  'cb982fca-cf7a-4f59-b9c7-55ca0364eddc'
).trim();

function installerBaseFromEnv() {
  const explicit = (env.VITE_INSTALLER_BASE_URL || '').trim().replace(/\/$/, '');
  if (explicit) return explicit;
  const supabaseUrl = url;
  const m = supabaseUrl.match(/https?:\/\/([^.]+)\./);
  if (m) {
    return `https://${m[1]}.supabase.co/storage/v1/object/public/waiver-installers`;
  }
  return '';
}

const installerBaseUrl = installerBaseFromEnv();

const waiverBody =
  '/* auto-generated by scripts/generate-legacy-waiver-config.cjs — do not commit */\n' +
  'window.__TAVARI_WAIVER_BROWSER_KIOSK__=' +
  JSON.stringify({
    supabaseUrl: url,
    anonKey: key,
    publicAppUrl: publicAppUrl || undefined,
    subdomainUrl: waiverSubdomainUrl || undefined
  }) +
  ';\n';

const dlBody =
  '/* auto-generated by scripts/generate-legacy-waiver-config.cjs — do not commit */\n' +
  'window.__TAVARI_LEGACY_DOWNLOADS__=' +
  JSON.stringify({
    installerBaseUrl: installerBaseUrl,
    waiverBrowserKioskUrl: waiverSubdomainUrl || undefined
  }) +
  ';\n';

const taskBody =
  '/* auto-generated by scripts/generate-legacy-waiver-config.cjs — do not commit */\n' +
  'window.__TAVARI_TASK_MANAGER_KIOSK__=' +
  JSON.stringify({
    supabaseUrl: url,
    anonKey: key,
    subdomainUrl: taskManagerSubdomainUrl || undefined
  }) +
  ';\n';

const punchBody =
  '/* auto-generated by scripts/generate-legacy-waiver-config.cjs — do not commit */\n' +
  'window.__TAVARI_LEGACY_PUNCHCLOCK__=' +
  JSON.stringify({
    supabaseUrl: url,
    anonKey: key,
    businessId: legacyPunchClockBusinessId || undefined,
    subdomainUrl: legacyPunchClockSubdomainUrl || undefined
  }) +
  ';\n';

if (!fs.existsSync(waiverOutDir)) {
  fs.mkdirSync(waiverOutDir, { recursive: true });
}
fs.writeFileSync(waiverOutFile, waiverBody, 'utf8');
if (!fs.existsSync(dlOutDir)) {
  fs.mkdirSync(dlOutDir, { recursive: true });
}
fs.writeFileSync(dlOutFile, dlBody, 'utf8');
if (!fs.existsSync(taskOutDir)) {
  fs.mkdirSync(taskOutDir, { recursive: true });
}
fs.writeFileSync(taskOutFile, taskBody, 'utf8');
if (!fs.existsSync(punchOutDir)) {
  fs.mkdirSync(punchOutDir, { recursive: true });
}
fs.writeFileSync(punchOutFile, punchBody, 'utf8');

if (!url || !key) {
  console.warn(
    '[legacy-waiver-config] VITE_SUPABASE_URL or VITE_SUPABASE_ANON_KEY missing — waiver browser kiosk will show a setup message.'
  );
} else {
  console.log('[legacy-waiver-config] wrote', path.relative(process.cwd(), waiverOutFile));
}
if (!installerBaseUrl) {
  console.warn(
    '[legacy-waiver-config] No VITE_INSTALLER_BASE_URL and could not derive from VITE_SUPABASE_URL — legacy downloads page will use same-origin /installers.'
  );
}
console.log('[legacy-waiver-config] wrote', path.relative(process.cwd(), dlOutFile));
console.log('[legacy-waiver-config] wrote', path.relative(process.cwd(), taskOutFile));
console.log('[legacy-waiver-config] wrote', path.relative(process.cwd(), punchOutFile));
