/**
 * Build Chrome OS / Linux print-helper packages for Supabase upload.
 * Outputs:
 *   dist/installers/Tavari-Receipt-Printer-ChromeOS-Install.sh  (self-contained; preferred)
 *   dist/installers/Tavari-Receipt-Printer-ChromeOS.zip         (optional offline bundle)
 */
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const root = path.join(__dirname, '..');
const outDir = path.join(root, 'dist', 'installers');
const stageDir = path.join(root, 'dist', 'chromeos-print-agent-stage');
const zipPath = path.join(outDir, 'Tavari-Receipt-Printer-ChromeOS.zip');
const shPath = path.join(outDir, 'Tavari-Receipt-Printer-ChromeOS-Install.sh');

const libSrc = path.join(root, 'tools', 'pos-print-agent', 'lib.cjs');
const serverSrc = path.join(root, 'tools', 'pos-print-agent', 'server.mjs');
const installSrc = path.join(root, 'tools', 'pos-print-agent', 'chromeos', 'install.sh');
const readmeSrc = path.join(root, 'tools', 'pos-print-agent', 'chromeos', 'README.md');

for (const file of [libSrc, serverSrc, installSrc]) {
  if (!fs.existsSync(file)) throw new Error(`Missing ${file}`);
}

fs.mkdirSync(outDir, { recursive: true });

const toLf = (text) => String(text).replace(/\r\n/g, '\n');
const libB64 = fs.readFileSync(libSrc).toString('base64');
const serverB64 = fs.readFileSync(serverSrc).toString('base64');

const selfContained = `#!/usr/bin/env bash
# Tavari Receipt Printer — Chrome OS / Linux self-contained installer
# Generated by scripts/build-pos-print-agent-chromeos.cjs — do not edit by hand.
# Usage (in Chrome OS Linux terminal):
#   curl -fsSL "<this-url>" | bash
# Or:
#   bash Tavari-Receipt-Printer-ChromeOS-Install.sh
set -euo pipefail

PORT="\${POS_PRINT_AGENT_PORT:-19100}"
HOST="\${POS_PRINT_AGENT_HOST:-0.0.0.0}"
INSTALL_DIR="\${HOME}/.local/share/tavari-pos-print-agent"
NODE_HOME="\${HOME}/.local/share/tavari-node"
UNIT_DIR="\${HOME}/.config/systemd/user"
UNIT_NAME="tavari-pos-print-agent.service"
NODE_VERSION="v20.18.1"

echo "=== Tavari Receipt Printer (Chrome OS / Linux) ==="
echo "Install dir: \${INSTALL_DIR}"

mkdir -p "\${INSTALL_DIR}" "\${UNIT_DIR}" "\${NODE_HOME}"

echo "Writing helper files..."
base64 -d <<'TAVARI_LIB_B64' > "\${INSTALL_DIR}/lib.cjs"
${libB64}
TAVARI_LIB_B64

base64 -d <<'TAVARI_SERVER_B64' > "\${INSTALL_DIR}/server.mjs"
${serverB64}
TAVARI_SERVER_B64

resolve_arch() {
  local machine
  machine="$(uname -m)"
  case "\${machine}" in
    x86_64|amd64) echo "x64" ;;
    aarch64|arm64) echo "arm64" ;;
    armv7l|armhf) echo "armv7l" ;;
    *)
      echo "Unsupported CPU architecture: \${machine}" >&2
      exit 1
      ;;
  esac
}

install_node_binary() {
  local arch="$1"
  local dist_name="node-\${NODE_VERSION}-linux-\${arch}"
  local url="https://nodejs.org/dist/\${NODE_VERSION}/\${dist_name}.tar.xz"
  local archive="\${NODE_HOME}/\${dist_name}.tar.xz"

  echo "Downloading Node \${NODE_VERSION} (\${arch})..."
  if command -v curl >/dev/null 2>&1; then
    curl -fsSL "\${url}" -o "\${archive}"
  elif command -v wget >/dev/null 2>&1; then
    wget -qO "\${archive}" "\${url}"
  else
    echo "Need curl or wget to download Node.js" >&2
    exit 1
  fi

  tar -xJf "\${archive}" -C "\${NODE_HOME}"
  rm -f "\${archive}"

  if [[ ! -x "\${NODE_HOME}/\${dist_name}/bin/node" ]]; then
    echo "Node binary missing after extract" >&2
    exit 1
  fi

  echo "\${NODE_HOME}/\${dist_name}/bin/node"
}

ensure_node() {
  if command -v node >/dev/null 2>&1; then
    command -v node
    return
  fi

  local existing
  existing="$(find "\${NODE_HOME}" -type f -path '*/bin/node' 2>/dev/null | head -n 1 || true)"
  if [[ -n "\${existing}" && -x "\${existing}" ]]; then
    echo "\${existing}"
    return
  fi

  echo "Node.js not found — downloading official binary (works on older Chrome OS Linux)..."
  install_node_binary "$(resolve_arch)"
}

NODE_BIN="$(ensure_node)"
NODE_VER="$("\${NODE_BIN}" -v 2>/dev/null || true)"
echo "Using Node: \${NODE_BIN} \${NODE_VER}"

cat > "\${INSTALL_DIR}/run.sh" <<EOF
#!/usr/bin/env bash
export POS_PRINT_AGENT_HOST="\${HOST}"
export POS_PRINT_AGENT_PORT="\${PORT}"
cd "\${INSTALL_DIR}"
exec "\${NODE_BIN}" "\${INSTALL_DIR}/server.mjs"
EOF
chmod +x "\${INSTALL_DIR}/run.sh"

if command -v systemctl >/dev/null 2>&1 && systemctl --user show-environment >/dev/null 2>&1; then
  cat > "\${UNIT_DIR}/\${UNIT_NAME}" <<EOF
[Unit]
Description=Tavari POS Receipt Printer Helper
After=network.target

[Service]
Type=simple
ExecStart=\${INSTALL_DIR}/run.sh
Restart=on-failure
RestartSec=3
Environment=POS_PRINT_AGENT_HOST=\${HOST}
Environment=POS_PRINT_AGENT_PORT=\${PORT}

[Install]
WantedBy=default.target
EOF

  systemctl --user daemon-reload
  systemctl --user enable --now "\${UNIT_NAME}" || true

  if command -v loginctl >/dev/null 2>&1; then
    loginctl enable-linger "$(whoami)" 2>/dev/null || true
  fi

  sleep 1
  if systemctl --user is-active --quiet "\${UNIT_NAME}"; then
    echo ""
    echo "Helper is running (systemd)."
  else
    echo "systemd start failed — starting helper in background instead..."
    nohup "\${INSTALL_DIR}/run.sh" >"\${INSTALL_DIR}/agent.log" 2>&1 &
    echo $! > "\${INSTALL_DIR}/agent.pid"
    sleep 1
  fi
else
  echo "systemd user services unavailable — starting helper in background..."
  nohup "\${INSTALL_DIR}/run.sh" >"\${INSTALL_DIR}/agent.log" 2>&1 &
  echo $! > "\${INSTALL_DIR}/agent.pid"
  mkdir -p "\${HOME}/.config/autostart"
  cat > "\${HOME}/.config/autostart/tavari-pos-print-agent.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=Tavari Receipt Printer
Exec=\${INSTALL_DIR}/run.sh
X-GNOME-Autostart-enabled=true
NoDisplay=true
EOF
  sleep 1
fi

if curl -fsS "http://127.0.0.1:\${PORT}/health" >/dev/null 2>&1 || curl -fsS "http://0.0.0.0:\${PORT}/health" >/dev/null 2>&1; then
  echo "Health check inside Linux: OK"
else
  echo "Warning: health check from inside Linux failed. Check \${INSTALL_DIR}/agent.log if present."
fi

echo ""
echo "IMPORTANT — reach this helper from Chrome on Chrome OS:"
echo "  1. In Linux, run: hostname -I"
echo "  2. Take the first IP (often 100.115.92.x)"
echo "  3. In Chrome open: http://THAT_IP:\${PORT}/health"
echo "  4. In Tavari Register Stations, set Print helper URL to http://THAT_IP:\${PORT}"
echo "  (Older Chromebooks often cannot use http://127.0.0.1:\${PORT} for Linux apps)"
echo ""
LINUX_IPS="$(hostname -I 2>/dev/null || true)"
if [[ -n "\${LINUX_IPS}" ]]; then
  FIRST_IP="$(echo "\${LINUX_IPS}" | awk '{print $1}')"
  echo "Detected Linux IP: \${FIRST_IP}"
  echo "Try in Chrome: http://\${FIRST_IP}:\${PORT}/health"
fi
echo ""
echo "In Tavari: POS → Settings → Register Stations → Use on this device"
echo "Done. Employees only tap Print after this."
`;

fs.writeFileSync(shPath, toLf(selfContained), { encoding: 'utf8', mode: 0o755 });
console.log(`Built ${shPath} (${(fs.statSync(shPath).size / 1024).toFixed(1)} KB)`);

// Also keep a zip for offline/manual use
fs.rmSync(stageDir, { recursive: true, force: true });
fs.mkdirSync(stageDir, { recursive: true });
fs.copyFileSync(libSrc, path.join(stageDir, 'lib.cjs'));
fs.copyFileSync(serverSrc, path.join(stageDir, 'server.mjs'));
fs.writeFileSync(path.join(stageDir, 'install.sh'), toLf(fs.readFileSync(installSrc, 'utf8')), 'utf8');
if (fs.existsSync(readmeSrc)) {
  fs.copyFileSync(readmeSrc, path.join(stageDir, 'README.md'));
}
fs.copyFileSync(shPath, path.join(stageDir, 'Tavari-Receipt-Printer-ChromeOS-Install.sh'));

fs.rmSync(zipPath, { force: true });
const isWin = process.platform === 'win32';
if (isWin) {
  execSync(
    `powershell -NoProfile -Command "Compress-Archive -Path '${stageDir.replace(/'/g, "''")}\\*' -DestinationPath '${zipPath.replace(/'/g, "''")}' -Force"`,
    { stdio: 'inherit' }
  );
} else {
  execSync(`cd "${stageDir}" && zip -r "${zipPath}" .`, { stdio: 'inherit' });
}
console.log(`Built ${zipPath}`);
fs.rmSync(stageDir, { recursive: true, force: true });
